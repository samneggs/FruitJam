#!/usr/bin/env python3
"""Build fluid_k.mpy: every fluid kernel plus the core1 worker, precompiled with mpy-cross 1.27
(armv7emsp), and upload it to the board. Importing a .mpy skips on-device parsing/compiling and,
imported first after a soft reset, puts the kernel code in SRAM."""
import shutil, subprocess, sys, os
from fluid_gen import VARIANTS

PICK = {'advect_uv': 'v0', 'advect_r': 'v0', 'divergence': 'v1a', 'pressure_rb': 'v0',
        'project': 'v0a', 'colorize': 'v0a', 'expand': 'v0a', 'splat': 'v0'}

def half(src, name, a, b):
    """Same kernel with half the rows; the caller shifts the base pointers for the bottom half."""
    assert src.count(a) == 1, (name, a)
    return src.replace(a, b).replace(f'def {name}(', f'def {name}_h(')

EXTRA = '''
@micropython.asm_thumb
def zero(r0, r1):                        # addr, words
    mov(r2, 0)
    align(4)
    label(L)
    str(r2, [r0, 0])
    add(r0, 4)
    sub(r1, 1)
    bne(L)

# core1 worker: never returns until told to. JOB (int32): seq, fn (fun_data|1), a0, a1, a2, done, a3.
# Sleeps in wfe; core0 writes a job, bumps seq and executes sev.  fn == 0 -> return.
@micropython.asm_thumb
def worker(r0):
    mov(r7, r0)
    ldr(r6, [r7, 0])                     # last seq seen
    label(WAIT)
    data(2, 0xBF20)                      # wfe
    ldr(r5, [r7, 0])
    cmp(r5, r6)
    beq(WAIT)
    mov(r6, r5)
    ldr(r4, [r7, 4])
    cmp(r4, 0)
    beq(EXIT)
    ldr(r0, [r7, 8])
    ldr(r1, [r7, 12])
    ldr(r2, [r7, 16])
    ldr(r3, [r7, 24])
    data(2, 0x47A0)                      # blx r4   (kernels save r4-r7, r10, r11 themselves)
    data(2, 0xF3BF, 0x8F5F)              # dmb sy
    str(r6, [r7, 20])                    # done = seq
    data(2, 0xBF40)                      # sev
    b(WAIT)
    label(EXIT)

@micropython.asm_thumb
def sev():
    data(2, 0xF3BF, 0x8F5F)              # dmb sy: job words visible before the event
    data(2, 0xBF40)                      # sev
'''

def build():
    src = '# generated by fluid_k_build.py - do not edit\n'
    src += ''.join(VARIANTS[k][v] for k, v in PICK.items())
    src += half(VARIANTS['divergence']['v1a'], 'divergence', 'mov(r5, 94)', 'mov(r5, 47)')
    src += half(VARIANTS['project']['v0a'], 'project', 'mov(r5, 94)', 'mov(r5, 47)')
    src += half(VARIANTS['colorize']['v0a'], 'colorize', 'movwt(r5, 12288)', 'movwt(r5, 6144)')
    src += half(VARIANTS['expand']['v0a'], 'expand', 'cmp(r5, 96)', 'cmp(r5, 48)')
    src += EXTRA
    open('fluid_k.py', 'w').write(src)
    mc = (shutil.which('mpy-cross') or os.path.expanduser('~/.local/bin/mpy-cross'))
    subprocess.run([mc, '-march=armv7emsp', '-o', 'fluid_k.mpy', 'fluid_k.py'], check=True)
    return os.path.getsize('fluid_k.py'), os.path.getsize('fluid_k.mpy')

if __name__ == '__main__':
    print('source %d bytes -> mpy %d bytes' % build())
    if '--upload' in sys.argv:
        from rp import Board
        b = Board(); b.soft_reset()
        print('uploaded', b.put('fluid_k.mpy', '/FluidFM/fluid_k.mpy'), 'bytes')
        out, err = b.exec("import sys\nif '/FluidFM' not in sys.path: sys.path.insert(0, '/FluidFM')   # the demo's modules live in /FluidFM\nimport fluid_k\nfrom machine import mem32\nprint({k: hex(mem32[id(getattr(fluid_k, k)) + 8] & 0xffffffff) for k in ('advect_uv', 'worker', 'expand_h')})")
        print(out, err); b.close()
